  private def adapterParamCType(tpe: AbiType): String = tpe match {
    case AbiType.Unit => "int32_t"
    case AbiType.Bool => "bool"
    case AbiType.Int8 => "int8_t"
    case AbiType.Int16 => "int16_t"
    case AbiType.Int32 => "int32_t"
    case AbiType.Int64 => "int64_t"
    case AbiType.Float32 => "float"
    case AbiType.Float64 => "double"
    case AbiType.String => "adapter_string_t *"
    case AbiType.Bytes => "adapter_list_u8_t *"
  }

  private def runtimeBoxMethodName(tpe: AbiType): String = tpe match {
    case AbiType.Bool => "flix_runtime_runtime_box_bool"
    case AbiType.Int8 => "flix_runtime_runtime_box_i8"
    case AbiType.Int16 => "flix_runtime_runtime_box_i16"
    case AbiType.Int32 => "flix_runtime_runtime_box_i32"
    case AbiType.Int64 => "flix_runtime_runtime_box_i64"
    case AbiType.Float32 => "flix_runtime_runtime_box_f32"
    case AbiType.Float64 => "flix_runtime_runtime_box_f64"
    case AbiType.String => "flix_runtime_runtime_box_string"
    case AbiType.Bytes => "flix_runtime_runtime_box_bytes"
    case other => throw new IllegalStateException(s"Unexpected box type: $other")
  }

  private def runtimeUnboxMethodName(tpe: AbiType): String = tpe match {
    case AbiType.Bool => "flix_runtime_runtime_unbox_bool"
    case AbiType.Int8 => "flix_runtime_runtime_unbox_i8"
    case AbiType.Int16 => "flix_runtime_runtime_unbox_i16"
    case AbiType.Int32 => "flix_runtime_runtime_unbox_i32"
    case AbiType.Int64 => "flix_runtime_runtime_unbox_i64"
    case AbiType.Float32 => "flix_runtime_runtime_unbox_f32"
    case AbiType.Float64 => "flix_runtime_runtime_unbox_f64"
    case AbiType.String => "flix_runtime_runtime_unbox_string"
    case AbiType.Bytes => "flix_runtime_runtime_unbox_bytes"
    case other => throw new IllegalStateException(s"Unexpected unbox type: $other")
  }

  private def boxExpr(tpe: AbiType, valueExpr: String): String = tpe match {
    case AbiType.Unit => "flix_runtime_runtime_box_i32(ctx, 0)"
    case other => s"${runtimeBoxMethodName(other)}(ctx, $valueExpr)"
  }

  private def unboxExpr(tpe: AbiType, borrowExpr: String): String = tpe match {
    case AbiType.Bool => s"flix_runtime_runtime_unbox_bool(ctx, $borrowExpr)"
    case AbiType.Int8 => s"flix_runtime_runtime_unbox_i8(ctx, $borrowExpr)"
    case AbiType.Int16 => s"flix_runtime_runtime_unbox_i16(ctx, $borrowExpr)"
    case AbiType.Int32 => s"flix_runtime_runtime_unbox_i32(ctx, $borrowExpr)"
    case AbiType.Int64 => s"flix_runtime_runtime_unbox_i64(ctx, $borrowExpr)"
    case AbiType.Float32 => s"flix_runtime_runtime_unbox_f32(ctx, $borrowExpr)"
    case AbiType.Float64 => s"flix_runtime_runtime_unbox_f64(ctx, $borrowExpr)"
    case other => throw new IllegalStateException(s"Unexpected scalar result type: $other")
  }

  private def resultTag(resultTpe: AbiType, suffix: String): String =
    s"EXPORTS_FLIX_EXPORTS_API_${cIdent(resultVariantName(resultTpe)).toUpperCase}_${suffix}"

  private def baseWitName(sym: String): String = {
    val segments = sym.split("\\.").toList.filter(_.nonEmpty)
    val raw = if (segments.isEmpty) sym else segments.mkString("-")
    raw
      .flatMap {
        case c if c.isLetterOrDigit => c.toString.toLowerCase
        case _ => "-"
      }
      .replaceAll("-{2,}", "-")
      .stripPrefix("-")
      .stripSuffix("-")
      .ensuring(_.nonEmpty, "wit export name cannot be empty")
  }

  private def uniqueWitName(base: String, defId: Long, used: mutable.Set[String]): String = {
    if (!used.contains(base)) {
      used += base
      base
    } else {
      val tagged = s"$base-$defId"
      used += tagged
      tagged
    }
  }

  private def cIdent(name: String): String =
    name.map {
      case c if c.isLetterOrDigit || c == '_' => c
      case _ => '_'
    }
}
