  private def renderCallMethod(entry: Entry): String = {
    val sb = new StringBuilder(2048)
    val cFuncName = s"exports_flix_exports_api_method_ctx_${cIdent(entry.witName)}"
    val resultCType = s"exports_flix_exports_api_${cIdent(resultVariantName(entry.signature.result))}_t"
    val paramDecls = entry.signature.params.zipWithIndex.map {
      case (tpe, idx) => s"${adapterParamCType(tpe)} a$idx"
    }

    sb.append(s"void $cFuncName(exports_flix_exports_api_borrow_ctx_t self")
    if (paramDecls.nonEmpty) sb.append(", ").append(paramDecls.mkString(", "))
    sb.append(s", $resultCType *ret) {\n")
    sb.append("  flix_runtime_runtime_borrow_ctx_t ctx = flix_runtime_runtime_borrow_ctx(self->runtime_ctx);\n")
    entry.signature.params.zipWithIndex.foreach {
      case (tpe, idx) =>
        val argName = s"a$idx"
        sb.append(s"  flix_runtime_runtime_own_value_t arg$idx = ${boxExpr(tpe, argName)};\n")
    }
    if (entry.signature.params.nonEmpty) {
      sb.append(s"  flix_runtime_runtime_borrow_value_t argv[${entry.signature.params.length}];\n")
      entry.signature.params.indices.foreach { idx =>
        sb.append(s"  argv[$idx] = flix_runtime_runtime_borrow_value(arg$idx);\n")
      }
    }
    sb.append(s"  flix_runtime_runtime_list_borrow_value_t args = { ${if (entry.signature.params.nonEmpty) "argv" else "0"}, ${entry.signature.params.length} };\n")
    sb.append("  flix_runtime_runtime_exec_t exec;\n")
    sb.append(s"  flix_runtime_runtime_invoke(ctx, ${entry.defId}ULL, &args, &exec);\n")
    entry.signature.params.indices.foreach { idx =>
      sb.append(s"  flix_runtime_runtime_value_drop_own(arg$idx);\n")
    }
    sb.append(renderTranslateRuntimeExec(entry.signature.result, "exec"))
    sb.append("}\n")
    sb.toString()
  }

  private def renderResumeMethod(entry: Entry): String = {
    val sb = new StringBuilder(1024)
    val cFuncName = s"exports_flix_exports_api_method_ctx_resume_${cIdent(entry.witName)}"
    val resultCType = s"exports_flix_exports_api_${cIdent(resultVariantName(entry.signature.result))}_t"
    sb.append(s"void $cFuncName(exports_flix_exports_api_borrow_ctx_t self, exports_flix_exports_api_own_suspension_t s, exports_flix_exports_api_borrow_value_t resume, $resultCType *ret) {\n")
    sb.append("  flix_runtime_runtime_borrow_ctx_t ctx = flix_runtime_runtime_borrow_ctx(self->runtime_ctx);\n")
    sb.append("  flix_runtime_runtime_own_suspension_t runtime_s = flix_api_take_suspension(s);\n")
    sb.append("  flix_runtime_runtime_exec_t exec;\n")
    sb.append("  flix_runtime_runtime_resume_ok_sync(ctx, runtime_s, flix_api_borrow_value(resume), &exec);\n")
    sb.append(renderTranslateRuntimeExec(entry.signature.result, "exec"))
    sb.append("}\n")
    sb.toString()
  }

  private def renderTranslateRuntimeExec(resultTpe: AbiType, execVar: String): String = {
    val sb = new StringBuilder(1024)
    sb.append(s"  switch ($execVar.tag) {\n")
    sb.append("    case FLIX_RUNTIME_RUNTIME_EXEC_OK:\n")
    resultTpe match {
      case AbiType.Unit =>
        sb.append(s"      ret->tag = ${resultTag(resultTpe, "OK")};\n")
        sb.append(s"      flix_runtime_runtime_exec_free(&$execVar);\n")
        sb.append("      return;\n")
      case AbiType.String =>
        sb.append(s"      ret->tag = ${resultTag(resultTpe, "OK")};\n")
        sb.append(s"      flix_runtime_runtime_unbox_string(ctx, flix_runtime_runtime_borrow_value($execVar.val.ok), &ret->val.ok);\n")
        sb.append(s"      flix_runtime_runtime_exec_free(&$execVar);\n")
        sb.append("      return;\n")
      case AbiType.Bytes =>
        sb.append(s"      ret->tag = ${resultTag(resultTpe, "OK")};\n")
        sb.append(s"      flix_runtime_runtime_unbox_bytes(ctx, flix_runtime_runtime_borrow_value($execVar.val.ok), &ret->val.ok);\n")
        sb.append(s"      flix_runtime_runtime_exec_free(&$execVar);\n")
        sb.append("      return;\n")
      case _ =>
        sb.append(s"      ret->tag = ${resultTag(resultTpe, "OK")};\n")
        val borrowExpr = s"flix_runtime_runtime_borrow_value($execVar.val.ok)"
        sb.append(s"      ret->val.ok = ${unboxExpr(resultTpe, borrowExpr)};\n")
        sb.append(s"      flix_runtime_runtime_exec_free(&$execVar);\n")
        sb.append("      return;\n")
    }
    sb.append("    case FLIX_RUNTIME_RUNTIME_EXEC_THROWN:\n")
    sb.append(s"      ret->tag = ${resultTag(resultTpe, "THROWN")};\n")
    sb.append(s"      ret->val.thrown = flix_api_wrap_value($execVar.val.thrown);\n")
    sb.append("      return;\n")
    sb.append("    case FLIX_RUNTIME_RUNTIME_EXEC_SUSPENDED:\n")
    sb.append(s"      ret->tag = ${resultTag(resultTpe, "SUSPENDED")};\n")
    sb.append(s"      ret->val.suspended = flix_api_wrap_suspension($execVar.val.suspended.suspension);\n")
    sb.append("      return;\n")
    sb.append("    default:\n")
    sb.append("      __builtin_trap();\n")
    sb.append("  }\n")
    sb.toString()
  }

  private def resultTypes(entries: List[Entry]): List[AbiType] =
    entries.iterator.map(_.signature.result).toSet.toList.sortBy((t: AbiType) => t.displayName)

  private def resultVariantName(tpe: AbiType): String = s"exec-${witTypeTag(tpe)}"

